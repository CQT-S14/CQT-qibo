def _qiskit_unitary(qasm):
    qiskit_qasm3 = pytest.importorskip("qiskit.qasm3")
    pytest.importorskip("qiskit_qasm3_import")
    from qiskit.quantum_info import Operator

    return Operator(qiskit_qasm3.loads(qasm)).reverse_qargs().data


@pytest.mark.parametrize("gate", QASM_GATES, ids=lambda gate: gate.__class__.__name__)
@pytest.mark.parametrize("reverse", [False, True])
def test_qasm3_gates_match_qiskit(backend, gate, reverse):
    nqubits = len(gate.qubits)
    if reverse:
        gate = gate.on_qubits({q: nqubits - 1 - q for q in range(nqubits)})
    circuit = Circuit(nqubits)
    circuit.add(gate)
    target = _qiskit_unitary(circuit.to_qasm3())
    unitary = backend.to_numpy(circuit.unitary(backend))
    # equal up to a global phase (only u2 and u3 differ by one)
    index = np.unravel_index(np.argmax(np.abs(unitary)), unitary.shape)
    phase = target[index] / unitary[index]
    np.testing.assert_allclose(unitary * phase, target, atol=1e-10)
    if gate.__class__.__name__ not in ("U2", "U3"):
        np.testing.assert_allclose(unitary, target, atol=1e-10)


def _qiskit_counts(circuit, shots=1000, **kwargs):
    qiskit_qasm3 = pytest.importorskip("qiskit.qasm3")
    pytest.importorskip("qiskit_qasm3_import")
    qiskit_aer = pytest.importorskip("qiskit_aer")

    qc = qiskit_qasm3.loads(circuit.to_qasm3(**kwargs))
    simulator = qiskit_aer.AerSimulator()
    counts = simulator.run(qc, shots=shots, seed_simulator=1234).result().get_counts()
    # keep the last declared register, which Qiskit prints first, with bit 0 first
    final = {}
    for key, value in counts.items():
        key = key.split(" ")[0][::-1]
        final[key] = final.get(key, 0) + value
    return final


def test_qiskit_active_reset():
    circuit = Circuit(1)
    circuit.add(gates.H(0))
    result = circuit.add(gates.M(0, collapse=True))
    circuit.add(gates.Condition(result.symbols[0], 1, gates.X(0)))
    circuit.add(gates.M(0))
    assert _qiskit_counts(circuit) == {"0": 1000}


def test_qiskit_feed_forward():
    circuit = Circuit(2)
    circuit.add(gates.H(0))
    result = circuit.add(gates.M(0, collapse=True))
    circuit.add(gates.Condition(result.symbols[0], 1, gates.X(1)))
    circuit.add(gates.M(0, 1))
    counts = _qiskit_counts(circuit)
    assert set(counts) == {"00", "11"}


@pytest.mark.parametrize("value", range(4))
def test_qiskit_register_value_order(value):
    """Prepare each two-qubit outcome and check which value triggers."""
    for prepared in range(4):
        circuit = Circuit(3)
        if prepared & 2:
            circuit.add(gates.X(0))
        if prepared & 1:
            circuit.add(gates.X(1))
        result = circuit.add(gates.M(0, 1, collapse=True))
        circuit.add(gates.Condition(result, value, gates.X(2)))
        circuit.add(gates.M(2))
        expected = "1" if prepared == value else "0"
        assert _qiskit_counts(circuit, shots=10) == {expected: 10}


def test_qiskit_reused_registers():
    circuit = Circuit(2)
    for _ in range(3):
        circuit.add(gates.H(0))
        result = circuit.add(gates.M(0, collapse=True))
        circuit.add(gates.Condition(result.symbols[0], 1, gates.X(0)))
        circuit.add(gates.Condition(result.symbols[0], 1, gates.X(1)))
    circuit.add(gates.M(0, 1))
    for reuse in (False, True):
        counts = _qiskit_counts(circuit, reuse_registers=reuse)
        # qubit 0 is always reset, qubit 1 flipped once per outcome 1
        assert {key[0] for key in counts} == {"0"}
        assert {key[1] for key in counts} == {"0", "1"}
