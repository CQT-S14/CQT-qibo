def test_qasm3_gate_definitions():
    circuit = Circuit(2)
    circuit.add(gates.MS(0, 1, 0.1, 0.2, 0.3))
    circuit.add(gates.RXX(0, 1, 0.4))
    circuit.add(gates.CU1(0, 1, 0.5))
    circuit.add(gates.PRX(1, 0.6, 0.7))
    circuit.add(gates.I(0, 1))
    lines = circuit.to_qasm3().splitlines()
    definitions = [
        line.split("(")[0].split(" ")[1] for line in lines if line.startswith("gate")
    ]
    # each custom gate defined once, before the gates that use it
    assert definitions == ["rxx", "ms", "r"]
    assert "cp(0.5) q[0], q[1];" in lines
    assert "r(0.6, 0.7) q[1];" in lines
    assert lines[-2:] == ["id q[0];", "id q[1];"]


def test_qasm2_regressions():
    """``to_qasm`` keeps its behaviour for final measurements."""
    circuit = Circuit(2)
    circuit.add(gates.H(0))
    circuit.add(gates.M(0, 1))
    assert circuit.to_qasm().endswith(
        "h q[0];\nmeasure q[0] -> register0[0];\nmeasure q[1] -> register0[1];"
    )


