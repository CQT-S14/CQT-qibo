"""Tests exporting circuits to OpenQASM 3, including conditional operations."""

import numpy as np
import pytest

from qibo import Circuit, __version__, gates

HEADER = f"""// Generated by QIBO {__version__}
OPENQASM 3.0;
include "stdgates.inc";
"""


def test_qasm3_empty():
    assert Circuit(2).to_qasm3() == HEADER + "qubit[2] q;"


def test_qasm3_gates_and_measurements():
    circuit = Circuit(3)
    circuit.add(gates.H(0))
    circuit.add(gates.CNOT(0, 2))
    circuit.add(gates.RX(1, 0.5))
    circuit.add(gates.M(2, 0, register_name="out"))
    target = HEADER + (
        "qubit[3] q;\n"
        "bit[2] out;\n"
        "h q[0];\n"
        "cx q[0], q[2];\n"
        "rx(0.5) q[1];\n"
        "out[0] = measure q[2];\n"
        "out[1] = measure q[0];"
    )
    assert circuit.to_qasm3() == target


def test_qasm3_condition_on_bit():
    circuit = Circuit(2)
    circuit.add(gates.H(0))
    result = circuit.add(gates.M(0, collapse=True))
    circuit.add(gates.Condition(result.symbols[0], 1, gates.X(1)))
    circuit.add(gates.Condition(result.symbols[0], 0, gates.RZ(1, 0.25)))
    circuit.add(gates.M(0, 1))
    target = HEADER + (
        "qubit[2] q;\n"
        "bit[1] register0;\n"
        "bit[2] register1;\n"
        "h q[0];\n"
        "register0[0] = measure q[0];\n"
        "if (register0[0]) {\n"
        "  x q[1];\n"
        "}\n"
        "if (!register0[0]) {\n"
        "  rz(0.25) q[1];\n"
        "}\n"
        "register1[0] = measure q[0];\n"
        "register1[1] = measure q[1];"
    )
    assert circuit.to_qasm3() == target


@pytest.mark.parametrize(
    "value,qasm_value", [(0, 0), (1, 4), (2, 2), (3, 6), ("100", 1), (7, 7)]
)
def test_qasm3_condition_on_register(value, qasm_value):
    """qibo values have the first measured bit as most significant, OpenQASM
    integers have bit 0 as least significant."""
    circuit = Circuit(4)
    result = circuit.add(gates.M(0, 1, 2, collapse=True))
    circuit.add(gates.Condition(result, value, gates.X(3)))
    assert f"if (register0 == {qasm_value}) {{" in circuit.to_qasm3()


def test_qasm3_multi_qubit_mid_circuit_measurement():
    circuit = Circuit(3)
    result = circuit.add(gates.M(2, 0, collapse=True))
    circuit.add(gates.Condition(result.symbols[0], 1, gates.X(1)))
    qasm = circuit.to_qasm3()
    # bits of collapsing measurements follow the sorted qubits, as their symbols
    assert "register0[0] = measure q[0];\nregister0[1] = measure q[2];" in qasm
    assert "bit[2] register0;" in qasm


def test_qasm3_implicit_mid_circuit_measurement():
    circuit = Circuit(1)
    circuit.add(gates.M(0))
    circuit.add(gates.X(0))
    circuit.add(gates.M(0))
    target = HEADER + (
        "qubit[1] q;\n"
        "bit[1] register0;\n"
        "bit[1] register1;\n"
        "register0[0] = measure q[0];\n"
        "x q[0];\n"
        "register1[0] = measure q[0];"
    )
    assert circuit.to_qasm3() == target


def test_qasm3_duplicate_register_names():
    circuit = Circuit(2)
    circuit.add(gates.M(0, collapse=True, register_name="a"))
    circuit.add(gates.M(1, collapse=True, register_name="a"))
    circuit.add(gates.M(1, register_name="a"))
    qasm = circuit.to_qasm3()
    assert "bit[1] a_1;\nbit[1] a_2;\nbit[1] a;" in qasm
    assert "a_1[0] = measure q[0];\na_2[0] = measure q[1];" in qasm
    assert qasm.endswith("a[0] = measure q[1];")


def test_qasm3_circuit_addition():
    circuit = Circuit(2)
    circuit.add(gates.H(0))
    result = circuit.add(gates.M(0, collapse=True))
    circuit.add(gates.Condition(result.symbols[0], 1, gates.X(1)))
    qasm = (circuit + circuit).to_qasm3()
    # the same measurement gate twice: each condition reads the latest one
    assert qasm.count("bit[1]") == 2
    assert "register0_1[0] = measure q[0];\nif (register0_1[0]) {" in qasm


@pytest.mark.parametrize("reuse", [False, True])
def test_qasm3_reuse_registers(reuse):
    circuit = Circuit(2)
    results = []
    for _ in range(3):
        circuit.add(gates.H(0))
        result = circuit.add(gates.M(0, collapse=True))
        circuit.add(gates.Condition(result.symbols[0], 1, gates.X(1)))
        results.append(result)
    # the first outcome is still needed after the third measurement
    circuit.add(gates.Condition(results[0].symbols[0], 1, gates.Z(1)))
    qasm = circuit.to_qasm3(reuse_registers=reuse)
    if reuse:
        assert qasm.count("bit[1]") == 2
        assert "register2" not in qasm
        # the third measurement overwrites the second one's register
        assert qasm.count("register1[0] = measure q[0];") == 2
    else:
        assert qasm.count("bit[1]") == 3
    assert qasm.endswith("if (register0[0]) {\n  z q[1];\n}")


def test_qasm3_unresolved_condition():
    result = Circuit(1).add(gates.M(0, collapse=True))
    circuit = Circuit(1)
    circuit.add(gates.Condition(result.symbols[0], 1, gates.X(0)))
    with pytest.raises(ValueError):
        circuit.to_qasm3()


def test_qasm3_condition_before_measurement():
    measurement = gates.M(0, collapse=True)
    circuit = Circuit(2)
    circuit.add(gates.Condition(measurement.result.symbols[0], 1, gates.X(1)))
    circuit.add(measurement)
    with pytest.raises(ValueError):
        circuit.to_qasm3()


@pytest.mark.parametrize(
    "gate,error",
    [
        (gates.H(1).controlled_by(0), ValueError),
        (gates.Unitary(np.eye(2), 0), NotImplementedError),
        (gates.RX(0, theta=0.1), None),
    ],
)
def test_qasm3_unsupported_gates(gate, error):
    circuit = Circuit(2)
    result = circuit.add(gates.M(1, collapse=True))
    circuit.add(gates.Condition(result.symbols[0], 1, gate))
    if error is None:
        circuit.to_qasm3()
        return
    with pytest.raises(error):
        circuit.to_qasm3()
    plain = Circuit(2)
    plain.add(gate)
    with pytest.raises(error):
        plain.to_qasm3()


def test_qasm3_symbolic_parameter():
    circuit = Circuit(2)
    result = circuit.add(gates.M(0, collapse=True))
    circuit.add(gates.RX(1, theta=np.pi * result.symbols[0]))
    with pytest.raises(ValueError):
        circuit.to_qasm3()


